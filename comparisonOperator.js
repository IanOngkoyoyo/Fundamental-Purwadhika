/* Comparison Operator
    Comparison operator digunakan untuk membandingkan dua nilai. 
    Hasil dari perbandingan ini adalah boolean (true/false).
    Operator perbandingan yang tersedia di JavaScript antara lain:
    - Sama dengan (==)
    - Sama dengan tipe data dan nilai (===)
    - Lebih besar dari (>)
    - Lebih kecil dari (<)
    - Lebih besar dari atau sama dengan (>=)
    - Lebih kecil dari atau sama dengan (<=)
    - Tidak sama dengan (!=)
    - Tidak sama dengan tipe data dan nilai (!==)
*/