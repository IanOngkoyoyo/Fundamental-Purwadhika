// Conditional = Diperuntukkan untuk decision

// if statement
if (100 > 10) {
  console.log('Benar');
}

// if else statement
if (100 > 10) {
  console.log('Benar');
} else {
  console.log('Salah');
}

//if.. else if.. else if... else
const studentScore = 90;
if (studentScore > 80) {
  console.log('Grade A');
} else if (studentScore > 70) {
  console.log('Grade B');
} else if (studentScore > 65) {
  console.log('Grade C');
} else {
  console.log('Tidak Lulus');
}


/* If else statement mengkonfirmasi boolean dari atas,
 jika sudah terpenuhi maka sistem tidak mengecek hingga bawah
 */